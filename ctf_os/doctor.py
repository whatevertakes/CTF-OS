"""Read-only local prerequisite diagnostics."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import shutil
import sys
from typing import Callable

from .config import AppConfig, ConfigError
from .contest_parser import ContestParseError, parse_contest
from .local_state import LocalState, StateError
from .sandbox.docker_cli import DockerCli
from .sandbox.broker import broker_transport_supported
from .solver_engine.codex_cli_backend import CodexCliBackend


@dataclass(frozen=True)
class DoctorCheck:
    name: str
    ok: bool
    required: bool
    detail: str


@dataclass(frozen=True)
class DoctorReport:
    checks: tuple[DoctorCheck, ...]

    @property
    def ok(self) -> bool:
        return all(check.ok or not check.required for check in self.checks)

    @property
    def exit_code(self) -> int:
        return 0 if self.ok else 1

    def render(self) -> str:
        return "\n".join(
            f"{'OK' if item.ok else ('FAIL' if item.required else 'WARN')} {item.name}: {item.detail}"
            for item in self.checks
        )


def run_doctor(
    config_path: str | Path,
    *,
    docker: DockerCli | None = None,
    which: Callable[[str], str | None] = shutil.which,
    strict_isolation_probe: Callable[[str], bool] = CodexCliBackend.strict_isolation_supported,
    require_non_mock: bool = False,
) -> DoctorReport:
    checks: list[DoctorCheck] = [
        DoctorCheck("python", sys.version_info >= (3, 11), True, f"{sys.version.split()[0]} (requires >=3.11)"),
        DoctorCheck("uv", which("uv") is not None, False, "found" if which("uv") else "not found; use an installed uv for documented commands"),
    ]
    try:
        config = AppConfig.from_file(config_path)
    except ConfigError as exc:
        checks.append(DoctorCheck("config", False, True, str(exc)))
        return DoctorReport(tuple(checks))
    checks.append(DoctorCheck("config", True, True, str(config.path)))
    non_mock = require_non_mock or (config.model_routing_enabled and config.sandbox_enabled)

    for label, root in (("incoming", config.incoming_root), ("output", config.output_root), ("sync", config.sync_root)):
        try:
            root.mkdir(parents=True, exist_ok=True)
            probe = root / ".ctf-os-doctor-write-test"
            probe.write_text("ok", encoding="utf-8")
            probe.unlink()
            checks.append(DoctorCheck(f"{label} writable", True, True, str(root)))
        except OSError as exc:
            checks.append(DoctorCheck(f"{label} writable", False, True, str(exc)))

    state_path = config.state_path()
    if state_path.is_file():
        try:
            LocalState.for_config(config)
            checks.append(DoctorCheck(
                "local state identity", True, True,
                f"team={config.team_id} member={config.member_name} contest={config.contest_name}: {state_path}",
            ))
        except (StateError, OSError) as exc:
            checks.append(DoctorCheck("local state identity", False, True, str(exc)))
    else:
        checks.append(DoctorCheck(
            "local state identity", True, True,
            f"not initialized yet; state migrate will bind {config.team_id}/{config.member_name}/{config.contest_name}",
        ))

    current_manifest = config.incoming_contest_dir() / "contest.md"
    manifests = [current_manifest] if current_manifest.is_file() else []
    if not manifests:
        checks.append(DoctorCheck("contest manifests", True, False, "none yet; add incoming/<contest>/contest.md"))
    for manifest in manifests:
        try:
            parse_contest(manifest)
            checks.append(DoctorCheck("contest manifest", True, True, str(manifest)))
        except ContestParseError as exc:
            # A starter template generated by init intentionally contains no
            # challenges, so it is a warning until the user adds challenge data.
            starter = "Add one ### category/challenge" in manifest.read_text(encoding="utf-8", errors="replace")
            checks.append(DoctorCheck("contest manifest", False, not starter, f"{manifest}: {exc}"))

    codex_found = which(config.codex_command) is not None
    checks.append(DoctorCheck("codex", codex_found, non_mock, "found" if codex_found else "not found; install it before a non-mock run"))
    if codex_found:
        strict_ok = strict_isolation_probe(config.codex_command)
        checks.append(DoctorCheck(
            "codex strict isolation", strict_ok, non_mock,
            "exact network-disabled named-profile isolation argv parses" if strict_ok else "installed Codex cannot parse the exact network-disabled named-profile isolation argv",
        ))
    else:
        checks.append(DoctorCheck("codex strict isolation", False, non_mock, "Codex command not found"))
    claude_found = which("claude") is not None
    checks.append(DoctorCheck("claude (optional)", claude_found, False, "found" if claude_found else "not installed"))

    adapter = docker or DockerCli()
    if config.sandbox_enabled:
        try:
            daemon_ok = adapter.daemon_available()
            daemon_detail = "available" if daemon_ok else "unavailable; --mock-worker remains available"
        except OSError as exc:
            daemon_ok, daemon_detail = False, f"unavailable ({exc}); --mock-worker remains available"
        checks.append(DoctorCheck("docker daemon", daemon_ok, non_mock, daemon_detail))
        try:
            image_ok = adapter.image_exists(config.sandbox_image) if daemon_ok else False
        except OSError:
            image_ok = False
        checks.append(DoctorCheck("sandbox image", image_ok, non_mock, config.sandbox_image if image_ok else f"missing {config.sandbox_image}"))
    else:
        checks.append(DoctorCheck("docker sandbox", not require_non_mock, require_non_mock, "disabled; non-mock runs are intentionally blocked"))
    broker_ok = broker_transport_supported()
    checks.append(DoctorCheck(
        "attempt filesystem spool transport", broker_ok, non_mock,
        "authenticated filesystem spool atomic publish available for the per-attempt broker" if broker_ok else "authenticated filesystem spool atomic publish unavailable; per-attempt broker cannot run",
    ))
    if not non_mock:
        checks.append(DoctorCheck("non-mock readiness", False, False, "not configured; enable model routing and sandbox, or pass --non-mock to require it"))
    else:
        required = [check for check in checks if check.required]
        checks.append(DoctorCheck("non-mock readiness", all(check.ok for check in required), True, "all required local prerequisites checked"))
    return DoctorReport(tuple(checks))
